const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const { chromium } = require(path.join(root, '.tools/revision-web/node_modules/playwright'));
const base = 'http://127.0.0.1:8011';
const fixtures = JSON.parse(fs.readFileSync(path.join(root, '.tools/review-browser-fixtures.json'), 'utf8'));
const credentials = fs.readFileSync(path.join(root, '.tools/acceso-inicial.txt'), 'utf8');
const email = credentials.match(/Correo: ([^\r\n]+)/)[1];
const password = credentials.match(/Contrase[^:]+: ([^\r\n]+)/u)[1];
const report = {comprobaciones:[],erroresJavascript:[],solicitudesExternas:[]};
let browser, page;
const check = label => { report.comprobaciones.push(label); console.log(label + ': OK'); };
(async () => {
    browser = await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe', headless:true});
    const context = await browser.newContext({viewport:{width:1600,height:1100}, deviceScaleFactor:1});
    context.on('request', request => { const url = new URL(request.url()); if (url.protocol.startsWith('http') && url.hostname !== '127.0.0.1') report.solicitudesExternas.push(url.origin); });
    page = await context.newPage();
    page.on('pageerror', error => report.erroresJavascript.push(error.message));
    let preventedNavigations = 0;
    page.on('dialog', async dialog => { if (dialog.type() === 'beforeunload') preventedNavigations++; else report.erroresJavascript.push('Dialogo inesperado'); await dialog.dismiss(); });
    const login = await page.goto(base + '/ingresar');
    assert.equal(login.status(), 200, 'El formulario debe responder HTTP 200');
    await page.getByLabel('Correo electrónico').fill(email);
    await page.getByLabel('Contraseña', {exact:true}).fill(password);
    await page.getByRole('button', {name:'Ingresar',exact:true}).click();
    await page.waitForURL('**/documentos');
    check('Ingreso real y enlace Revisar en listado');
    assert.ok(await page.getByRole('link',{name:'Revisar',exact:true}).count() > 0);
    const review = base + '/documentos/' + fixtures.pdf + '/revision';
    await page.goto(review);
    await page.waitForFunction(() => !!document.querySelector('#pdf-surface canvas')?.width && document.getElementById('preview-status').textContent.startsWith('Página'), null, {timeout:30000});
    assert.equal(await page.locator('#extracted-text').getAttribute('readonly'), '');
    check('PDF local renderizado en canvas y extracción de solo lectura');
    const before = await page.locator('canvas').evaluate(canvas => canvas.width);
    await page.locator('#zoom-in').click();
    await page.waitForFunction(width => document.querySelector('canvas')?.width > width, before);
    assert.equal(await page.locator('#zoom-label').textContent(), '125 %');
    check('Zoom de PDF');
    await page.locator('#next-page').click();
    await page.waitForURL('**/revision?pagina=2');
    await page.waitForFunction(() => document.getElementById('preview-status').textContent.startsWith('Página 2'),null,{timeout:30000});
    assert.equal(await page.locator('#page-label').textContent(),'Página 2 de 2');
    assert.equal(await page.locator('#variant option').count(),2);
    await page.locator('#variant').selectOption('1');
    const selected = (await page.evaluate(() => JSON.parse(document.getElementById('review-data').textContent).variantes[1].texto)).replace(/\r\n?/g,'\n');
    assert.equal(await page.locator('#extracted-text').inputValue(),selected);
    check('Navegación sincronizada y selección de variante OCR');
    const stale = await context.newPage();
    stale.on('pageerror', error => report.erroresJavascript.push(error.message));
    await stale.goto(review + '?pagina=2');
    if ((await page.locator('#reference-text').inputValue()).length === 0) {
        await page.locator('#copy-draft').click();
        assert.equal(await page.locator('#reference-text').inputValue(),selected);
        check('Copia explícita como borrador');
    }
    const reference = '  Transcripción sintética de prueba.\nOficio 001-2026-GADPRI\nMaría Pérez  ';
    const notes = 'PRUEBA AUTOMATIZADA; no es una evaluación institucional. Ejecución ' + Date.now();
    await page.locator('#reference-text').fill(reference);
    await page.locator('#reference-notes').fill(notes);
    await page.locator('#previous-page').click({noWaitAfter:true});
    await page.waitForFunction(() => document.getElementById('draft-state').textContent.includes('sin guardar'));
    assert.ok(preventedNavigations > 0);
    assert.ok(page.url().endsWith('pagina=2'));
    assert.equal(await page.locator('#reference-text').inputValue(),reference);
    check('Aviso antes de abandonar cambios sin guardar');
    const saved = page.waitForResponse(response => response.url().endsWith('/referencia') && response.request().method()==='POST');
    await page.locator('#save-reference').click();
    assert.equal((await saved).status(),200);
    await page.waitForFunction(() => document.getElementById('save-message').textContent.includes('guardada'));
    assert.equal(await page.locator('#draft-state').textContent(),'Sin cambios pendientes');
    check('Guardado real por HTTP con CSRF');
    await stale.locator('#reference-text').fill('Borrador concurrente que no debe reemplazar la versión guardada.');
    const conflict = stale.waitForResponse(response => response.url().endsWith('/referencia') && response.request().method()==='POST');
    await stale.locator('#save-reference').click();
    assert.equal((await conflict).status(),409);
    await stale.waitForFunction(() => document.getElementById('save-message').textContent.includes('Otra persona'));
    assert.ok((await stale.locator('#reference-text').inputValue()).startsWith('Borrador concurrente'));
    await stale.close();
    check('Edición concurrente rechazada sin perder el borrador');
    await page.reload();
    await page.waitForFunction(() => document.getElementById('preview-status').textContent.startsWith('Página 2'),null,{timeout:30000});
    assert.equal(await page.locator('#reference-text').inputValue(),reference);
    assert.ok(await page.getByText('Historial de referencias', {exact:false}).count());
    await page.screenshot({path:path.join(root,'.tools/revision-desktop.png'),fullPage:true});
    check('Persistencia exacta de referencia y captura de escritorio');
    const noCsrf = await context.request.post(base + '/documentos/' + fixtures.pdf + '/referencia', {data:{numero_pagina:2,texto_referencia:'No guardar',revision:null}});
    assert.equal(noCsrf.status(),419);
    check('CSRF real rechaza guardado sin token');
    await page.getByRole('link',{name:'Ver texto completo',exact:true}).click();
    assert.ok(await page.getByRole('heading',{name:'Página 1',exact:true}).count());
    assert.ok(await page.getByRole('heading',{name:'Página 2',exact:true}).count());
    assert.ok(!(await page.locator('main').innerText()).includes('Transcripción sintética de prueba.'));
    check('Texto completo por páginas separado de la referencia');
    await page.goto(base + '/documentos/' + fixtures.imagen + '/revision');
    await page.waitForFunction(() => document.getElementById('original-image')?.naturalWidth > 0);
    const imageWidth = await page.locator('#original-image').evaluate(image => image.clientWidth);
    await page.locator('#zoom-in').click();
    await page.waitForFunction(width => document.getElementById('original-image').clientWidth > width,imageWidth);
    check('Vista previa y zoom de PNG autenticado');
    const mobile = await browser.newContext({viewport:{width:390,height:844},isMobile:true,deviceScaleFactor:1,storageState:await context.storageState()});
    const phone = await mobile.newPage();
    phone.on('pageerror', error => report.erroresJavascript.push(error.message));
    await phone.goto(review + '?pagina=2');
    await phone.waitForFunction(() => document.getElementById('preview-status').textContent.startsWith('Página 2'),null,{timeout:30000});
    const dimensions = await phone.evaluate(() => ({scroll:document.documentElement.scrollWidth,width:innerWidth}));
    assert.ok(dimensions.scroll <= dimensions.width + 1, 'No debe desbordar horizontalmente en móvil');
    assert.ok(await phone.locator('#save-reference').isVisible());
    await phone.screenshot({path:path.join(root,'.tools/revision-mobile.png'),fullPage:true});
    check('Vista móvil sin desbordamiento y captura');
    assert.deepEqual(report.erroresJavascript,[]);
    assert.deepEqual(report.solicitudesExternas,[]);
    check('Sin errores JavaScript ni solicitudes externas');
    fs.writeFileSync(path.join(root,'.tools/revision-browser-report.json'),JSON.stringify(report,null,2));
    await browser.close();
})().catch(async error => {
    console.error(error.message);
    if (page) {
        console.error('Vista previa:', await page.locator('#preview-status').textContent({timeout:1000}).catch(()=>''));
        console.error('Errores JS:', JSON.stringify(report.erroresJavascript));
        await page.screenshot({path:path.join(root,'.tools/revision-browser-failure.png'),fullPage:true}).catch(()=>{});
    }
    if (browser) await browser.close();
    process.exitCode=1;
});
